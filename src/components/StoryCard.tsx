import { useEffect, useState } from 'react'
import { PLACE_BY_ID } from '../lib/data'
import type { Plan } from '../lib/planner'
import { requestStory, type StoryResult } from '../lib/story/client'
import { useApp } from '../state'
import { Icon } from './Icon'

const canSpeak = typeof window !== 'undefined' && 'speechSynthesis' in window

export function StoryCard({ plan }: { plan: Plan }) {
  const { profile, settings, story, setStory } = useApp()
  const res: StoryResult | null = story?.planAt === plan.createdAt ? story.result : null
  const [busy, setBusy] = useState(false)
  const [speaking, setSpeaking] = useState(false)

  useEffect(() => () => { if (canSpeak) window.speechSynthesis.cancel() }, [plan.createdAt])

  async function tell() {
    setBusy(true)
    try { setStory({ planAt: plan.createdAt, result: await requestStory(plan, profile, { offline: settings.offline }) }) } finally { setBusy(false) }
  }

  function listen() {
    if (!res || !canSpeak) return
    const synth = window.speechSynthesis
    if (speaking) { synth.cancel(); setSpeaking(false); return }
    const s = res.story
    const parts = [s.title, s.intro, ...s.segments.map((x) => x.text), s.outro].filter(Boolean)
    parts.forEach((t, i) => {
      const u = new SpeechSynthesisUtterance(t)
      u.lang = 'en-GB'
      u.rate = 0.98
      if (i === parts.length - 1) u.onend = () => setSpeaking(false)
      synth.speak(u)
    })
    setSpeaking(true)
  }

  if (!res) {
    return (
      <div className="card card-pad story-card" style={{ marginTop: 16 }}>
        <p className="eyebrow" style={{ margin: 0 }}>Every route has a story</p>
        <p className="small muted" style={{ margin: '6px 0 12px' }}>
          Turn these stops into one narrated walk, written only from the sourced notes behind each place.
        </p>
        <button className="btn btn-primary" onClick={tell} disabled={busy}>
          {busy ? <span className="spinner" /> : <Icon name="sparkle" size={16} />} {busy ? 'Writing your story… (up to a minute)' : 'Tell me the story of this walk'}
        </button>
      </div>
    )
  }

  const s = res.story
  const g = s.generator
  return (
    <div className="card card-pad story-card fade-in" style={{ marginTop: 16 }} aria-live="polite">
      <div className="row spread wrap" style={{ gap: 8 }}>
        <span className={`badge ${g.kind === 'model' ? 'badge-model' : 'badge-estimate'}`} title={g.kind === 'model' ? 'Generated by the configured model and checked against our sources' : 'No model was used'}>
          <Icon name="sparkle" size={14} />
          {g.kind === 'model' ? `Written by ${g.model}${g.provider ? ` · ${g.provider}` : ''}${g.pregenerated ? ` · pre-generated ${g.pregenerated}` : g.latencyMs ? ` · ${(g.latencyMs / 1000).toFixed(1)} s` : ''}` : 'Offline story from TRAILS notes (no AI)'}
        </span>
        {canSpeak && (
          <button className="btn btn-ghost btn-sm" onClick={listen} aria-pressed={speaking}>
            <Icon name={speaking ? 'pause' : 'play'} size={14} /> {speaking ? 'Stop' : 'Listen'}
          </button>
        )}
      </div>
      {res.fallbackReason && <p className="tiny muted" style={{ marginTop: 6 }}>{res.fallbackReason}</p>}
      <h3 className="story-title">{s.title}</h3>
      {s.intro && <p className="story-text">{s.intro}</p>}
      {s.segments.map((x) => (
        <p className="story-text" key={x.placeId}>
          <b>{PLACE_BY_ID[x.placeId]?.name}.</b> {x.text}
          {x.cite.map((n) => <sup key={n}><a href={`#story-src-${n}`} className="cite">[{n}]</a></sup>)}
        </p>
      ))}
      {s.outro && <p className="story-text">{s.outro}</p>}
      {s.sources.length > 0 && (
        <ol className="tiny muted story-sources">
          {s.sources.map((x) => (
            <li key={x.n} id={`story-src-${x.n}`} value={x.n}><a href={x.url} target="_blank" rel="noreferrer">{x.title}</a></li>
          ))}
        </ol>
      )}
      <button className="btn btn-ghost btn-sm" onClick={tell} disabled={busy}>
        {busy ? <span className="spinner" /> : <Icon name="refresh" size={14} />} Retell
      </button>
    </div>
  )
}
